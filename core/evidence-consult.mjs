// 验不了（输入造不出来 / 分支走不到）另加
export const INPUT = [
  '这一支要的输入在真实业务里由谁产生（哪个上游模块、哪个用户动作）？',
  '有没有测试账号、地区、开关或调试入口能让这个输入为真？',
  '注入的输入会不会被上游覆盖或过滤？过滤点在哪？',
  '这一支在当前配置下是不是根本没挂上（没下发、没路由、被熔断）？那它是该挂没挂，还是本期刻意不放？',
];

/** 判据面：按断言文字（和观测配方名）命中的类别，按命中先后排；一个都不中给「界面」兜底（界面是默认验法） */
export function facesOf(text) {
  const t = String(text || '');
  // 按命中次数排：一条断言常顺带提到别的词（「下发」「对照」），只取最像的两类，列满所有类等于没给方向
  const scored = FACES.map(f => ({ f, n: (t.match(new RegExp(f.match.source, 'gi')) || []).length })).filter(x => x.n > 0)
    .sort((a, b) => b.n - a.n);
  if (!scored.length) return [FACES[0]];
  return scored.filter((x, i) => i === 0 || (i === 1 && x.n * 2 >= scored[0].n)).map(x => x.f);
}

/**
 * 一条断言的取证咨询。
 * @param {object} a { assert, via, why_not_ui, op, situation: 'gap'|'blocked', gaps:[], unlock, text }
 */
export function consultFor(a = {}) {
  // 判据面只看断言本身和它的观测配方：卡住的说明（unlock / actual）里常提一堆旁的东西，会把类别拉散
  const basis = [a.assert, a.op, a.why_not_ui].filter(Boolean).join('\n');
  const faces = facesOf(basis);
  const surfaces = faces.flatMap(f => f.surfaces.map(([where, ask]) => ({ face: f.id, where, ask })));
  const questions = [...GENERIC, ...(a.situation === 'blocked' ? INPUT : [])];
  const opts = [...new Set(surfaces.map(s => s.where))].slice(0, 4);
  const owner_ask = {
    question: `「${clip(a.assert, 60)}」这条，业务上在哪里能看到它？`,
    why: a.situation === 'blocked'
      ? `执行者造不出它要的输入 / 看不到它的结果，需要你说明这块业务在哪里体现、怎么触发`
      : `执行者找不到能看到这个结论的入口（${(a.gaps || []).join('、') || '缺证据'}），需要你指一个能看到它的地方`,
    options: [...opts.map(o => `${o} => 我照这个入口取证`), '都没有，需要加一个观测点 => 记成产品缺口（finding），由你定加不加'],
  };
  return { faces: faces.map(f => ({ id: f.id, label: f.label })), surfaces, questions, owner_ask };
}

const clip = (s, n) => { const t = String(s || '').replace(/\s+/g, ' ').trim(); return t.length > n ? t.slice(0, n) + '…' : t; };
